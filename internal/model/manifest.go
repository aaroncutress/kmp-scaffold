// schema1 is the shape of the manifest before templates existed. It is frozen:
// projects generated by earlier versions of the tool still have this on disk,
// and this struct is the only thing that can read them.
type schema1 struct {
	GeneratorVer  string `json:"generatorVersion"`
	Name          string `json:"name"`
	Package       string `json:"package"`
	ApplicationID string `json:"applicationId"`
	Android       bool   `json:"android"`
	IOS           bool   `json:"ios"`
	AndroidLayout string `json:"androidLayout"`
	IOSLayout     string `json:"iosLayout"`

	SharedUtils   []string `json:"sharedUtils"`
	AndroidExtras []string `json:"androidExtras"`
	Packs         []string `json:"packs"`
	RootTabs      []string `json:"rootTabs"`

	Features []struct {
		Name         string `json:"name"`
		Android      bool   `json:"android"`
		Shared       bool   `json:"shared"`
		IOS          bool   `json:"ios,omitempty"`
		Presentation string `json:"presentation"`
		RootTab      bool   `json:"rootTab"`
	} `json:"features"`
}

// BuiltinKMPTemplate is the id of the template every schema-1 project was
// generated from - there was only one.
const BuiltinKMPTemplate = "kmp-mobile"

func migrateManifest(data []byte, schema int) (*Manifest, error) {
	var old schema1
	if err := json.Unmarshal(data, &old); err != nil {
		return nil, fmt.Errorf("parsing a schema-%d manifest: %w", schema, err)
	}

	// Everything that used to be a manifest field becomes the KMP template's
	// vars, under the same JSON names, so the projection is lossless and the
	// template reads it with no special cases.
	vars := map[string]any{
		"android":       old.Android,
		"ios":           old.IOS,
		"androidLayout": old.AndroidLayout,
		"iosLayout":     old.IOSLayout,
		"sharedUtils":   nonNil(old.SharedUtils),
		"androidExtras": nonNil(old.AndroidExtras),
		"packs":         nonNil(old.Packs),
		"rootTabs":      nonNil(old.RootTabs),
	}

	m := Manifest{
		Schema:       ManifestSchema,
		GeneratorVer: old.GeneratorVer,
		Template:     TemplateRef{ID: BuiltinKMPTemplate, Source: "builtin"},
		Project: Project{
			Name:          old.Name,
			Package:       old.Package,
			ApplicationID: old.ApplicationID,
		},
		Migrated: true,
	}
	if err := m.SetVars(vars); err != nil {
		return nil, err
	}

	for _, f := range old.Features {
		rec, err := NewFeature("feature", f.Name, map[string]any{
			"android":      f.Android,
			"shared":       f.Shared,
			"ios":          f.IOS,
			"presentation": f.Presentation,
			"rootTab":      f.RootTab,
		})
		if err != nil {
			return nil, err
		}
		m.Features = append(m.Features, rec)
	}
	return &m, nil
}

// nonNil keeps an absent list distinguishable from an empty one in the encoded
// vars: a schema-1 manifest with no packs meant "none", not "unset".
func nonNil(v []string) []string {
	if v == nil {
		return []string{}
	}
	return v
}
